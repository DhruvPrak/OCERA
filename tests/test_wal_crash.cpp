#ifndef NOMINMAX
#define NOMINMAX
#endif
#include <windows.h>

// Prevent Windows macros from colliding with OCERA enum values.
#undef CREATE_NEW
#undef OPEN_EXISTING
#endif

namespace {

void Require(bool condition, const std::string& message) {
    if (!condition) {
        throw std::runtime_error(message);
    }
}

void WriteValue(ocera::BufferPoolManager& bpm, ocera::page_id_t page_id,
                const std::string& value, std::uint64_t txn_id) {
    ocera::Page* page = bpm.FetchPage(page_id);
    Require(page != nullptr, "could not fetch page for write");
    std::memset(page->data, 0, ocera::PAGE_SIZE);
    std::memcpy(page->data, value.data(), value.size());
    Require(bpm.UnpinPage(page_id, true, txn_id),
            "could not append page update to WAL");
}

std::string ReadValue(ocera::BufferPoolManager& bpm, ocera::page_id_t page_id) {
    ocera::Page* page = bpm.FetchPage(page_id);
    Require(page != nullptr, "could not fetch page for read");
    const std::string value(page->data);
    Require(bpm.UnpinPage(page_id, false), "could not unpin read page");
    return value;
}

// This function runs in a child process. _Exit deliberately bypasses C++
// destructors, including DatabaseInstance and its stream-owning members.
int RunCrashChild(const std::string& scenario, const std::string& db_file) {
    using namespace ocera;
    DatabaseInstance db(db_file, 4, DatabaseOpenMode::CREATE_NEW);

    page_id_t page_id = INVALID_PAGE_ID;
    Page* page = db.GetBufferPoolManager().NewPage(&page_id);
    Require(page != nullptr, "could not allocate crash-test page");
    std::memset(page->data, 0, PAGE_SIZE);
    std::memcpy(page->data, "baseline", 9);
    Require(db.GetBufferPoolManager().UnpinPage(page_id, true),
            "could not log baseline page image");
    Require(db.GetBufferPoolManager().FlushPage(page_id),
            "could not flush baseline page");
    db.GetDiskManager().Sync();

    TransactionManager& tm = db.GetTransactionManager();
    const txn_id_t txn = tm.Begin();
    Require(tm.Lock(txn, page_id, LockMode::Exclusive),
            "could not acquire exclusive page lock");

    if (scenario == "commit-before-page-flush") {
        WriteValue(db.GetBufferPoolManager(), page_id, "committed", txn);
        Require(tm.Commit(txn), "could not durably commit child transaction");
    } else if (scenario == "loser-wal-only") {
        WriteValue(db.GetBufferPoolManager(), page_id, "uncommitted", txn);
        Require(db.GetLogManager().FlushUpTo(db.GetLogManager().GetLastLSN()),
                "could not force loser WAL records");
    } else if (scenario == "loser-after-page-flush") {
        WriteValue(db.GetBufferPoolManager(), page_id, "uncommitted", txn);
        Require(db.GetBufferPoolManager().FlushPage(page_id),
                "could not flush loser data page");
    } else {
        throw std::runtime_error("unknown crash-test child scenario");
    }

    // The parent process verifies recovery after this abrupt process exit.
    std::_Exit(0);
}

std::string QuoteArgument(const std::string& value) {
    // Test paths are generated by the OS and do not contain embedded quotes.
    return "\"" + value + "\"";
}

void RunScenario(const std::string& executable,
                 const std::string& scenario,
                 const std::string& expected) {
    using namespace ocera;
    const auto stamp = std::chrono::steady_clock::now().time_since_epoch().count();
    const auto path = std::filesystem::temp_directory_path() /
        ("ocera_wal_crash_" + scenario + "_" + std::to_string(stamp) + ".db");
    const std::string db_file = path.string();
#ifdef _WIN32
    // Launch directly with CreateProcessA. This avoids cmd.exe interpreting
    // spaces in the executable and database paths as argument separators.
    STARTUPINFOA startup_info{};
    startup_info.cb = sizeof(startup_info);

    PROCESS_INFORMATION process_info{};

    const std::string command_line =
        QuoteArgument(executable) + " --crash-child " +
        scenario + " " + QuoteArgument(db_file);

    std::vector<char> mutable_command_line(
        command_line.begin(), command_line.end());
    mutable_command_line.push_back('\0');

    const BOOL created = CreateProcessA(
        executable.c_str(),
        mutable_command_line.data(),
        nullptr,
        nullptr,
        FALSE,
        0,
        nullptr,
        nullptr,
        &startup_info,
        &process_info);

    Require(created != 0,
            "CreateProcessA failed with error " +
            std::to_string(GetLastError()));

    const DWORD wait_result =
        WaitForSingleObject(process_info.hProcess, INFINITE);

    DWORD child_exit_code = 1;
    const BOOL exit_code_read =
        wait_result == WAIT_OBJECT_0 &&
        GetExitCodeProcess(process_info.hProcess, &child_exit_code);

    CloseHandle(process_info.hThread);
    CloseHandle(process_info.hProcess);

    Require(exit_code_read != 0,
            "could not retrieve crash child exit code");

    const int child_status = static_cast<int>(child_exit_code);
#else
    const std::string command = QuoteArgument(executable) + " --crash-child " +
        scenario + " " + QuoteArgument(db_file);
    const int child_status = std::system(command.c_str());
#endif

    Require(child_status == 0,
            "crash child failed for scenario: " + scenario);

    try {
        DatabaseInstance recovered(db_file, 4, DatabaseOpenMode::OPEN_EXISTING);
        page_id_t page_id = INVALID_PAGE_ID;
        // The first user page follows the reserved header and allocation pages.
        page_id = 2;
        const std::string actual = ReadValue(recovered.GetBufferPoolManager(), page_id);
        Require(actual == expected,
                "unexpected recovered value for " + scenario +
                ": expected '" + expected + "', got '" + actual + "'");
    } catch (...) {
        std::error_code ignored;
        std::filesystem::remove(db_file, ignored);
        std::filesystem::remove(db_file + ".wal", ignored);
        throw;
    }

    std::error_code ignored;
    std::filesystem::remove(db_file, ignored);
    std::filesystem::remove(db_file + ".wal", ignored);
}

}  // namespace

int main(int argc, char** argv) {
    try {
        if (argc == 4 && std::string(argv[1]) == "--crash-child") {
            return RunCrashChild(argv[2], argv[3]);
        }
        Require(argc == 1, "unexpected command-line arguments");
        const std::string executable =
            std::filesystem::absolute(std::filesystem::path(argv[0])).string();

        // A durable COMMIT must be redone even though the dirty data page was
        // never flushed before the child process terminated.
        RunScenario(executable, "commit-before-page-flush", "committed");

        // A durable loser WAL record must be undone even when its data page
        // never reached the database file.
        RunScenario(executable, "loser-wal-only", "baseline");

        // WAL-before-data permits a loser page to reach disk before process
        // death; recovery must still restore its before-image.
        RunScenario(executable, "loser-after-page-flush", "baseline");

        std::cout << "WAL abrupt-process-crash tests passed.\n";
        return 0;
    } catch (const std::exception& exception) {
        std::cerr << "WAL abrupt-process-crash tests failed: "
                  << exception.what() << '\n';
        return 1;
    }
}
